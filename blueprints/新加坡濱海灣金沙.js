// 正面（朝海灣的西面，−z）：三棟很高的直立板樓並排，頂上一條長長的白色「船身」橫跨三棟；
//   北端（模型的 +x，四視圖正面那一格的左邊）船頭往外伸、懸在半空，越往外越窄、越薄
// 側面（從北邊 +x 看）：前面（西）那一面筆直；後面（東）那一面從塔底一路往上彎進來（塔底寬、塔頂窄），
//   下半段兩腳之間透空成倒 V，到約 42% 高（第 23 層）併攏；頂上是船身斷面、上面一排樹
// 三樣識別物：①兩腳張開的倒 V（直腳＋彎腳，中間透空）②橫跨三棟、船頭懸出去的空中花園船身
//   ③船上沿前緣的長條藍色無邊際泳池和一排樹
// 比例表（實物，H ＝ 塔高 ≈ 194 m、55 層）：
//   空中花園長 340 m（1.75H）、寬 38～40 m（0.2H）、在約 200 m 高；北端懸挑約 66.5 m（0.34H）
//   兩腳在第 23 層併攏（0.42H）；無邊際泳池約 146～150 m（0.75H）；塔「底寬、往上收窄」
//   以下查不到、照一般認識估：每棟沿船身方向寬約 46 m（0.24H）、兩棟間空隙約 64 m（0.33H）；
//   每隻腳厚約 15 m（0.08H）；塔頂深 0.16H，東立面往下一路外彎到塔底深 0.42H，地面兩腳空隙 0.2H；
//   船身厚實物約 0.05H，加厚到約 0.1H 才看得出船形；樹放大到約 0.1H 高才看得見
// 輪廓寬度（正面，以船身全長 ＝ 1）：地面 0.79（三棟各 0.14＋兩道空隙各 0.19，底下一條低矮深色大廳）
//   ／塔身中段 0.79（空隙透空）／塔頂 0.79／船身 1.00（北端船頭佔 0.19、越往外越薄）
// 輪廓寬度（側面，以塔底深 ＝ 1）：地面 1.00（直腳 0.18＋空隙 0.41＋彎腳 0.41）／0.25H 高 0.82／
//   0.42H 高 0.59／0.7H 高 0.45／塔頂 0.35／船身 0.47
// 部件尺寸（第一版報告 9000 塊 s = 10.23；這一版塔變重，估 s ≈ 9.2）：塔高 H=dim(s,4,14)=37、
//   塔寬 dim(s,0.96,4)=9、空隙 dim(s,1.32,4)=12、腳厚 dim(s,0.32,2)=3、東面外彎 dim(s,1.04,4)=10、
//   地面空隙 dim(s,0.8,3)=7、併攏高 dim(s,1.68,6)=15、船身厚 dim(s,0.42,2)=4、船頭懸挑 dim(s,1.36,5)=13、
//   泳池 dim(s,3,10)=28 長 × dim(s,0.2,2)=2 寬、樹冠直徑 3、樹高 4～5、空中餐廳 dim(s,0.5,3)=5 寬
// 部件（六層）：
//   台基：三棟底下連通的低矮大廳（walls＋box，深色玻璃）
//   主量體：西腳（box，直的）、東腳（逐層 walls，內緣直線收攏、外緣彎）、併攏後的上段（逐層 walls，東面繼續往上彎進來）
//   開口：兩腳之間透空的倒 V 中庭；一層玻璃一層樓板的橫向窗帶（顏色函式）
//   線腳分層：船身白色側緣、甲板邊緣一圈白、船頭底面陰影色
//   屋頂：空中花園船身（逐欄 box：中段等寬、北端收窄收薄成船頭、南端收圓成船尾）
//   頂飾與附屬：無邊際泳池（顏色函式）、一排高低不一的樹（box＋blob，rowOf 排）、兩座空中餐廳（box）
customBlueprint({
  name: '新加坡濱海灣金沙',
  pal: ['#d3d9dc',   // 0 塔樓立面：白色樓板與窗框
        '#7c95a6',   // 1 塔樓玻璃窗帶
        '#dde0dc',   // 2 空中花園船身（白）、餐廳屋頂
        '#9aa3a8',   // 3 船頭底面陰影
        '#c4aa82',   // 4 甲板（木平台）
        '#1d78b8',   // 5 無邊際泳池
        '#3d7a35',   // 6 樹冠
        '#6b4f33',   // 7 樹幹
        '#4a5d6e'],  // 8 大廳、空中餐廳的深色玻璃
  lo: 2.5, hi: 16,

  gen(v, s) {
    // ---- 尺寸：全部照比例表換算（H ＝ 塔高）----
    const H  = dim(s, 4.0, 14);                    // 塔高（到船身底）
    const Wt = dim(s, 0.96, 4);                    // 每棟沿 x 的寬
    const G  = dim(s, 1.32, 4);                    // 兩棟之間的空隙
    const T  = dim(s, 0.32, 2);                    // 西腳厚度（沿 z）；塔頂深 2T
    const De = dim(s, 1.04, 4);                    // 塔底的東立面比塔頂多伸出去幾格
    const Gb = dim(s, 0.80, 3);                    // 地面那一層兩腳之間的空隙（≤ De）
    const yj = Math.min(dim(s, 1.68, 6), H - 4);   // 兩腳併攏的高度（第 23 層）
    const th = dim(s, 0.42, 2);                    // 船身厚
    const ov = dim(s, 0.10, 1);                    // 船身比塔頂前後各寬出幾格
    const Lc = dim(s, 1.36, 5);                    // 北端船頭懸挑長
    const so = dim(s, 0.12, 1);                    // 南端船尾超出幾格
    const Lp = dim(s, 3.00, 10);                   // 泳池長
    const pw = dim(s, 0.20, 2);                    // 泳池寬
    const hl = dim(s, 0.20, 1);                    // 底部大廳高

    const P  = Wt + G;                             // 塔距
    const xN = 2 * P + Wt - 1;                     // 北棟（+x）外牆那一欄
    const xS = -so;                                // 船尾那一欄
    const xE = xN + Lc;                            // 船頭尖那一欄
    const yt = H + th - 1;                         // 甲板面那一層
    const za = -ov, zb = 2 * T - 1 + ov;           // 船身前後緣（塔頂佔 z 0～2T−1）
    const xP0 = Math.max(xS + 2, xN - Lp + 1);     // 泳池南端（泳池一路到北棟外牆）
    const band = (x, y, z) => ((H - 1 - y) % 2 === 0 ? 1 : 0);   // 一層玻璃一層樓板，最上面那層是玻璃
    // 東立面（後面那一面）在第 y 層的 z：塔底最外、往上一路彎進來，到塔頂剛好是 2T−1
    const zOut = y => 2 * T - 1 + Math.round(De * Math.pow(1 - y / H, 1.5));

    // ---- 台基：三棟底下連通的低矮大廳，只佔兩腳之間最底下那一兩層 ----
    v.walls(xN / 2, 0, T + (Gb - 1) / 2, xN + 1, hl, Gb, 8, 1);
    v.box(xN / 2, hl - 1, T + (Gb - 1) / 2, xN + 1, 1, Gb, 8);

    // ---- 三棟塔樓 ----
    for (let i = 0; i < 3; i++) {
      const xc = i * P + (Wt - 1) / 2;
      v.box(xc, 0, (T - 1) / 2, Wt, yj, T, band);                 // 西腳（前，直的）
      for (let y = 0; y < yj; y++) {                                // 東腳（後）：內緣直線收攏成倒 V，外緣跟著東立面彎
        const zi = T + Math.round(Gb * (1 - y / yj)), zo = zOut(y);
        v.walls(xc, y, (zi + zo) / 2, Wt, 1, zo - zi + 1, band, 2);
      }
      for (let y = yj; y < H; y++) {                                // 併攏之後：一整棟，東面繼續往上收
        const zo = zOut(y);
        v.walls(xc, y, zo / 2, Wt, 1, zo + 1, band, 2);
      }
    }

    // ---- 空中花園船身：一欄一欄畫，中段等寬；北端船頭收窄收薄、南端船尾收圓 ----
    for (let x = xS; x <= xE; x++) {
      let cut = 0, yb = H;
      if (x > xN) {
        const t = (x - xN) / Lc;
        cut = Math.round(Math.pow(t, 1.3) * ((zb - za + 1) / 2 - 1));   // 船頭先寬後尖，像船首
        yb = H + Math.round(t * (th - 1));                               // 底面往船頭斜上去
      } else if (x < xS + 2) {
        cut = xS + 2 - x;
        if (x === xS) yb = H + 1;
      }
      const z0 = za + cut, z1 = zb - cut;
      v.box(x, yb, (z0 + z1) / 2, 1, yt - yb + 1, z1 - z0 + 1, (cx, y, z) => {
        if (y === yt) {
          if (cx >= xP0 && cx <= xN && z <= za + pw - 1) return 5;  // 無邊際泳池，貼著前緣
          return (z === z0 || z === z1) ? 2 : 4;                    // 邊緣一圈白、中間甲板
        }
        return (cx > xN && y === yb) ? 3 : 2;                       // 船頭底面陰影、其餘白色船身
      });
    }

    // ---- 樹：沿甲板後緣一排，高低大小錯開，不要像一排柵欄 ----
    const rT = Math.max(1.3, s * 0.14), trH = dim(s, 0.20, 2), sp = dim(s, 0.42, 3);
    const tree = (x, z, i) => {
      const h = trH + (i % 3 === 1 ? 1 : 0), r = rT * (i % 2 ? 1.12 : 1);
      v.box(x, yt + 1, z, 1, h, 1, 7);
      blob(v, x, yt + 1 + h, z, r, r, r, 6);
    };
    const nT = Math.max(2, Math.floor((xN - xS - 1) / sp));
    rowOf(v, nT, sp, (vv, p, i) => tree(Math.round(p), zb - 1, i), (xS + 1 + xN) / 2);

    // ---- 空中餐廳：南段兩座低矮玻璃亭，白色平屋頂 ----
    const pwd = dim(s, 0.5, 3), ph = dim(s, 0.12, 1);
    const pz0 = za + 1, pz1 = Math.max(za + 1, zb - 3);
    const pav = x => {
      v.box(x, yt + 1, (pz0 + pz1) / 2, pwd, ph, pz1 - pz0 + 1, 8);
      v.box(x, yt + 1 + ph, (pz0 + pz1) / 2, pwd + 2, 1, pz1 - pz0 + 1, 2);
    };
    rowOf(v, 2, (xP0 - xS) / 2, (vv, p) => pav(Math.round(p)), (xS + xP0 - 1) / 2);
  }
});
