/* 範例：哥德式小教堂
   照著這支改就能做自己的。兩個重點：

   1. gen(v, s) —— 每個尺寸都用 s 重新算一次，不是把一張固定的圖放大縮小。
      這樣 300 塊跟 10000 塊看起來才會是同一座教堂，只是刻得比較細。
   2. 部件要分層 —— 台基、牆、扶壁、窗、簷、屋頂、鐘樓、尖頂、十字架，
      一件一件疊上去。voxel 建築「像不像」幾乎全靠部件數，不是靠塊數。 */
customBlueprint({
  name: '範例小教堂',
  pal: ['#d8d0c0',   // 0 石牆（亮）
        '#9c9384',   // 1 台基、扶壁、簷（暗一階，用來分層）
        '#4a5a68',   // 2 屋頂與尖頂（青石板）
        '#bfe0f2',   // 3 窗玻璃
        '#d9a441',   // 4 玫瑰窗外框、小尖塔、十字架（金）
        '#6b4a2f'],  // 5 木門
  lo: 2.2, hi: 15.5, // s 的掃描範圍，遊戲會在這中間找最接近目標塊數的尺寸

  gen(v, s) {
    /* 靠中線對稱的東西寬度取奇數（dim 第四個參數）：屋頂每層縮 2 格，
       偶數的話屋脊會歪；鐘樓偶數的話尖頂與十字架會偏半格。
       深度不取奇數——兩個維度都逼成奇數的話塊數一跳就是好幾十，中段目標對不上。 */
    const nw = dim(s, 1.50, 7, true);     // 中殿寬
    const nd = dim(s, 2.05, 9);           // 中殿深
    const nh = dim(s, 1.25, 4);           // 中殿牆高
    const tw = dim(s, 0.85, 5, true);     // 鐘樓邊長
    const th = dim(s, 2.35, 9);           // 鐘樓牆高（要明顯高過中殿屋脊才看得出是鐘樓）
    const sp = dim(s, 1.00, 4);           // 尖頂高

    /* 鐘樓黏在中殿正面（−z 那頭），交疊 1 格：完全分開的話兩棟之間會有一條縫，
       看起來是兩棟房子而不是一座教堂。 */
    const tz = -Math.round((nd + tw) / 2) + 1;
    const face = tz - (tw - 1) / 2;       // 鐘樓正面那片牆的 z
    const side = (nw - 1) / 2;            // 中殿側牆的 x

    /* ── 台基 ───────────────────────────────────────────────
       整座站在一片實心上。遊戲會把最低那層貼到地面，不必自己保證 y=0，
       但「最底層有幾格」要夠——只靠幾格站著的話，那幾格一掉就整座報廢。 */
    v.box(0, 0, 0, nw + 2, 1, nd + 2, 1);
    v.box(0, 0, tz, tw + 2, 1, tw + 2, 1);

    // ── 中殿：四面牆 + 側面的哥德長窗 ───────────────────────
    v.walls(0, 1, 0, nw, nh, nd, 0, 1);
    const win = { rows: 1, w: dim(s, 0.14, 1), h: dim(s, 0.55, 2), c: 3,
                  cols: dim(s, 0.30, 2), stepX: dim(s, 0.62, 3),
                  y: 1 + dim(s, 0.30, 2), axis: 'z' };
    /* windowGrid 走 tint（只在已經有牆的格子上換色），所以牆不在那裡就什麼都不會畫。
       兩片側牆各叫一次，x 給牆面的位置。 */
    mirrorX(v, side, (vv, dx) => windowGrid(vv, Object.assign({ x: dx, z: 0 }, win)));

    /* ── 扶壁 ───────────────────────────────────────────────
       貼在側牆外面的一排短柱，頂端收一階。這是哥德教堂最好認的特徵之一，
       而且它讓側牆有凹凸，遠看才不是一片平板。 */
    const nb = dim(s, 0.28, 2);           // 每側幾根
    const bs = Math.max(2, Math.round((nd - 2) / nb));
    const bd = dim(s, 0.16, 1);           // 扶壁的厚度（沿 z）
    mirrorX(v, side + 1, (vv, dx) => {
      for (let i = 0; i < nb; i++) {
        const bz = Math.round(-(nd - 1) / 2 + 1 + (i + 0.5) * bs);
        vv.box(dx, 1, bz, 1, nh, bd, 1);
        vv.box(dx, 1 + nh, bz, 1, 1, Math.max(1, bd - 1), 1);   // 收一階當頂
      }
    });

    // ── 簷與屋頂 ───────────────────────────────────────────
    v.box(0, 1 + nh, 0, nw + 2, 1, nd + 2, 1);          // 壓頂：牆與屋頂之間的深色分界
    v.gable(0, 2 + nh, 0, nw + 2, nd + 2, 2);           // 兩坡屋頂，寬多 2 格當屋簷

    // ── 鐘樓 ───────────────────────────────────────────────
    v.walls(0, 1, tz, tw, th, tw, 0, 1);

    /* 大門：arch 的 c 給了就會先補一片比開口大一圈的牆再挖，
       所以這一下同時做出「石框 + 拱形洞」。後面再補一片木門把洞擋起來。 */
    const dw = dim(s, 0.36, 3, true);                   // 門寬（奇數，拱心才不會落在兩格之間）
    const dh = dim(s, 0.55, 2);                         // 直柱段高（總高還要加上拱頂 (dw−1)/2）
    arch(v, 0, 1, face, dw, dh, 1, 1);
    v.box(0, 1, face + 1, dw, dh + (dw - 1) / 2, 1, 5); // 門板：塞在洞後面一格

    /* 鐘室開口的高度先算出來，玫瑰窗才知道自己能擺多高。
       兩件事都在同一片牆上，各自從「塔頂」與「門頂」量的話一定會撞在一起——
       實測撞過一次：鐘室的洞把玫瑰窗的上半圈整個挖掉，只剩一個 U 形金框。 */
    const bw = dim(s, 0.34, 3, true);
    const bh = dim(s, 0.50, 2);
    const by = 1 + th - bh - Math.round(bw / 2) - 1;

    /* 玫瑰窗：門上方那個圓窗。畫在牆面上要用 tint（只在有牆的格子上換色）——
       用 v.set 的話，算出來落在牆外的那幾格會變成懸空的孤格。 */
    const rr0 = dim(s, 0.26, 2);
    const ry = Math.min(1 + dh + (dw - 1) / 2 + rr0 + dim(s, 0.16, 2),
                        by - rr0 - 2);            // 壓在鐘室開口下面，留 2 格牆
    for (let i = -rr0; i <= rr0; i++) for (let j = -rr0; j <= rr0; j++) {
      const q = Math.hypot(i, j);
      if (q > rr0 + 0.35) continue;
      tint(v, i, ry + j, face, q > rr0 - 1 ? 4 : 3);    // 外圈金框、裡面玻璃
    }

    /* 鐘室開口：四面都開。arch 的牆厚是沿 z 算的，所以只有正背兩面能用它；
       左右兩面自己 carve 一個方洞再收一階當拱頂。 */
    mirrorZ(v, (tw - 1) / 2, (vv, dz) => arch(vv, 0, by, tz + dz, bw, bh, 1));
    mirrorX(v, (tw - 1) / 2, (vv, dx) => {
      vv.carve(dx, by, tz, 1, bh, bw);
      vv.carve(dx, by + bh, tz, 1, 1, Math.max(1, bw - 2));
    });

    /* ── 塔頂：簷 → 四角小尖塔 → 尖頂 → 十字架 ───────────────
       小尖塔與十字架是最後那一點「像不像」的差別，塊數卻很少。 */
    v.box(0, 1 + th, tz, tw + 2, 1, tw + 2, 1);
    /* 四角小尖塔：細一點、矮一點。r0 給 1.1 那版是三格粗六格高，
       遠看像四根立在塔頂的金柱子，不像尖塔。 */
    const pin = dim(s, 0.30, 3);
    corners4(v, (tw + 1) / 2, (tw + 1) / 2, (vv, x, z) =>
      vv.taper(x, 2 + th, tz + z, 0.9, 0.4, pin, 4));
    v.taper(0, 2 + th, tz, (tw + 2) / 2, 0.5, sp, 2);   // 尖頂
    const cy = 2 + th + sp;                             // 十字架站在尖頂的尖端上
    const ch = dim(s, 0.30, 3);
    v.box(0, cy, tz, 1, ch, 1, 4);
    v.box(0, cy + Math.max(1, ch - 2), tz, 3, 1, 1, 4);   // 橫臂：離尖端 2 格，小尺寸才不會變成 T 字

    /* ── 台階 ───────────────────────────────────────────────
       stairs 每一階都填實到底，不會變成懸空踏面。dir 'z' = 往 +z 邊走邊變高，
       所以起點放在鐘樓正面前方 ns 格，最高那階剛好接到台基。 */
    const ns = dim(s, 0.20, 2);
    stairs(v, 0, 0, face - ns, ns, dim(s, 0.55, 3, true), 'z', 1);
  }
});
